import test from 'node:test';
import assert from 'node:assert/strict';
import {once} from 'node:events';
import {fixture} from './release-fixture.mjs';
import {releaseHTTP} from '../release/http.mjs';
import {wire} from '../release/policy.mjs';
import {HTTPTransport} from '../protocol/http.mjs';
import {ReleaseClient} from '../release/client.mjs';
import {ReleaseDelivery} from '../release/delivery.mjs';

test('HTTP approval boundary uses secure cookies, exact CSIL review, and current session', async t => {
  const f = fixture(), server = releaseHTTP({recorder: f.recorder, resolveKey: f.resolveKey});
  t.after(async () => {server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); f.close();});
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const endpoint = `http://127.0.0.1:${server.address().port}`;
  const page = await fetch(endpoint);
  assert.equal(page.status, 200); assert.match(await page.text(), /Approve this exact candidate/);
  assert.equal(page.headers.get('x-frame-options'), 'DENY'); assert.equal(page.headers.get('referrer-policy'), 'no-referrer');
  assert.equal((await fetch(`${endpoint}/?candidate=${f.value.candidateId}`)).status,200);
  const discovery = new HTTPTransport(`${endpoint}/csil/v1/rpc`, {codec: wire});
  const description = wire.fromServiceDescriptionCbor(await discovery.call('Discovery', 'describe', wire.toDescribeRequestCbor({versions: ['0alpha1'], requiredFeatures: ['human-exact-candidate']})));
  assert(description.authenticatedOperations.includes('Releases/approve'));
  const rpc = async (op, type, payload, headers = {}) => fetch(`${endpoint}/csil/v1/rpc`, {method: 'POST', headers: {'content-type': 'application/cbor', ...headers}, body: wire.encodeValue(new Map([['v', 1], ['id', 7], ['service', 'Releases'], ['op', op], ['payload', {tag: 24, value: wire[`to${type}Cbor`](payload)}]]))});
  const unpack = async (r, type) => {assert.equal(r.status, 200); const env = wire.decode(new Uint8Array(await r.arrayBuffer())); assert.equal(env.get('id'), 7); assert.equal(env.get('variant'), type); return wire[`from${type}Cbor`](env.get('payload').value);};
  assert.equal((await rpc('begin-login', 'ReleaseLoginStart', {identity: f.config.login_hint})).status, 403);
  const start = await rpc('begin-login', 'ReleaseLoginStart', {identity: f.config.login_hint}, {origin: f.origin});
  const loginCookie = start.headers.getSetCookie()[0];
  assert.match(loginCookie, /__Host-opal-release-login=.+; Path=\/; Secure; HttpOnly; SameSite=Lax/);
  const login = new URL((await unpack(start, 'ReleaseLoginStarted')).redirectUrl);
  const callback = new URL(login.searchParams.get('callback_url')); callback.searchParams.set('encrypted_token', login.searchParams.get('nonce'));
  const complete = await fetch(`${endpoint}${callback.pathname}${callback.search}`, {headers: {cookie: loginCookie.split(';')[0]}, redirect: 'manual'});
  assert.equal(complete.status, 303); assert.match(complete.headers.get('location'), /^https:\/\/approval\.catalystsquad\.local\/#csrf=/);
  const csrf = new URLSearchParams(new URL(complete.headers.get('location')).hash.slice(1)).get('csrf');
  const cookie = complete.headers.getSetCookie().find(c => c.startsWith('__Host-opal-release-session=')).split(';')[0];
  const headers = {origin: f.origin, cookie, 'x-opal-csrf': csrf};
  const bytes = wire.toReleaseCandidateCbor(f.value);
  assert.equal((await rpc('review', 'ReleaseReview', {candidate: bytes}, headers)).status, 403, 'old upload endpoint is disabled');
  assert.equal((await rpc('review-candidate', 'ReleaseCandidateRef', {candidateId:f.value.candidateId}, headers)).status, 403, 'submission is required');
  const submission = f.client.packet('submit', 'ReleaseSubmission', {candidate:bytes});
  await unpack(await rpc('submit', 'SignedRecord', submission), 'ReleaseSubmitted');
  assert.equal((await rpc('review-candidate', 'ReleaseCandidateRef', {candidateId:f.value.candidateId}, {origin:f.origin,cookie})).status, 403);
  const review = await unpack(await rpc('review-candidate', 'ReleaseCandidateRef', {candidateId:f.value.candidateId}, headers), 'ReleaseReviewed');
  const packet = await unpack(await rpc('approve', 'ReleaseApprove', {reviewId: review.reviewId, digest: review.digest, commandKey: 'browser-command'}, headers), 'SignedRecord');
  const a = wire.fromReleaseApprovalCbor(wire.fromSignatureInputCbor(packet.input).body);
  assert.equal(a.human.accountId, f.config.approver.account_id); assert.deepEqual(a.candidate, bytes);
  const client = new ReleaseClient({endpoint:`${f.origin}/csil/v1/rpc`, recorder:f.app, controller:f.controller, signer:f.controllerKey, resolveKey:f.resolveKey, now:f.now,
    call: async (op, packet, type) => unpack(await rpc(op, 'SignedRecord', packet), type)});
  const submitted=await client.submit(bytes), direct=await f.client.submit(bytes);
  assert.equal(submitted.reviewUrl,direct.reviewUrl);assert.deepEqual(Buffer.from(submitted.digest),Buffer.from(direct.digest));
  f.startController();const delivery = new ReleaseDelivery({controller:f.execution,client,now:f.now});
  for(let i=0;i<12;i++){await delivery.tick();f.advance(1100);if(f.execution.read(f.value.candidateId).terminal)break;}
  assert.equal(f.execution.read(f.value.candidateId).body.phase,'healthy');assert.equal(f.changes.length,1);
  assert.deepEqual(await client.events(),[]);
  assert.equal((await fetch(`${endpoint}${callback.pathname}${callback.search}`, {headers: {cookie: loginCookie.split(';')[0]}, redirect: 'manual'})).status, 403);
  const withdrawn = await unpack(await rpc('withdraw', 'ReleaseWithdraw', {approvalId: a.approvalId}, headers), 'ReleaseWithdrawn');
  assert.equal(withdrawn.approvalId, a.approvalId);
});
