// Command dispatchgen writes server dispatch tables for csilgen Go packages.
//
// It reads client.gen.go in a package directory. For each generated client
// method, it records the service name, operation name, request type, and
// response decoder. It writes dispatch.gen.go with one function per service:
//
//	func <Service>Ops(impl <Service>) map[string]func(context.Context, []byte) ([]byte, error)
//
// The table comes from the generated client, so it covers every operation.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type op struct {
	name, method, req, resp string
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: dispatchgen <generated-package-dir>")
		os.Exit(2)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "dispatchgen:", err)
		os.Exit(1)
	}
}

func run(dir string) error {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, filepath.Join(dir, "client.gen.go"), nil, 0)
	if err != nil {
		return err
	}
	services := map[string][]op{}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || fn.Body == nil || len(fn.Type.Params.List) != 2 {
			continue
		}
		reqType, ok := fn.Type.Params.List[1].Type.(*ast.Ident)
		if !ok {
			continue
		}
		var service, name, resp string
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			if sel, ok := call.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "Call" && len(call.Args) == 4 {
				service, _ = strconv.Unquote(call.Args[1].(*ast.BasicLit).Value)
				name, _ = strconv.Unquote(call.Args[2].(*ast.BasicLit).Value)
			}
			if id, ok := call.Fun.(*ast.Ident); ok && strings.HasPrefix(id.Name, "Decode") {
				resp = strings.TrimPrefix(id.Name, "Decode")
			}
			return true
		})
		if service == "" || resp == "" {
			continue
		}
		services[service] = append(services[service], op{name: name, method: fn.Name.Name, req: reqType.Name, resp: resp})
	}
	if len(services) == 0 {
		return fmt.Errorf("no client methods found in %s", dir)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by dispatchgen; DO NOT EDIT.\n\npackage %s\n\nimport \"context\"\n\n", f.Name.Name)
	names := make([]string, 0, len(services))
	for s := range services {
		names = append(names, s)
	}
	sort.Strings(names)
	for _, s := range names {
		fmt.Fprintf(&b, "// %sOps returns the server dispatch table for %s.\n", s, s)
		fmt.Fprintf(&b, "func %sOps(impl %s) map[string]func(context.Context, []byte) ([]byte, error) {\n", s, s)
		fmt.Fprintf(&b, "\treturn map[string]func(context.Context, []byte) ([]byte, error){\n")
		for _, o := range services[s] {
			fmt.Fprintf(&b, "\t\t%q: func(ctx context.Context, b []byte) ([]byte, error) {\n", o.name)
			fmt.Fprintf(&b, "\t\t\treq, err := Decode%s(b)\n\t\t\tif err != nil {\n\t\t\t\treturn nil, &DecodeError{Err: err}\n\t\t\t}\n", o.req)
			fmt.Fprintf(&b, "\t\t\tresp, err := impl.%s(ctx, req)\n\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n", o.method)
			fmt.Fprintf(&b, "\t\t\treturn Encode%s(resp), nil\n\t\t},\n", o.resp)
		}
		fmt.Fprintf(&b, "\t}\n}\n\n")
	}
	fmt.Fprintf(&b, "// DecodeError reports a request that does not match the contract.\n")
	fmt.Fprintf(&b, "type DecodeError struct{ Err error }\n\n")
	fmt.Fprintf(&b, "func (e *DecodeError) Error() string { return \"invalid request: \" + e.Err.Error() }\n\n")
	fmt.Fprintf(&b, "// StatusCode lets transports map a decode failure to a client error.\n")
	fmt.Fprintf(&b, "func (e *DecodeError) StatusCode() int { return 400 }\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "dispatch.gen.go"), out, 0o644)
}
