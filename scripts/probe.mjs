import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { DiscoveryAsyncClient } from '../.build/client.async.gen.js';
import { HTTPTransport } from '../protocol/http.mjs';
const endpoint=process.argv[2];if(!endpoint)throw Error('Usage: node scripts/probe.mjs https://host/csil/v1/rpc');
const client=new DiscoveryAsyncClient(new HTTPTransport(endpoint));
const d=await client.describe({versions:['0alpha1'],requiredFeatures:['strict-cbor']});
const s=await client.readSchema({schema:d.schema});
assert.deepEqual(Buffer.from(s.descriptor),readFileSync(new URL('../generated/go/magi.csil-schema.cbor',import.meta.url)));
console.log(JSON.stringify({protocol:d.protocol,operations:d.implementedOperations,descriptorDigest:Buffer.from(d.schema.digest).toString('hex'),descriptor:'matched'}));
